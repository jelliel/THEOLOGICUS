const fs = require("fs");
const L = [];
L.push("");
L.push("  /* ── 3. validation du spritesheet SVG (profil restreint, comme OpenPets) ── */");
L.push("  var SVG_EL = {};");
L.push("  [\"svg\", \"g\", \"defs\", \"path\", \"rect\", \"circle\", \"ellipse\", \"line\", \"polyline\", \"polygon\",");
L.push("   \"linearGradient\", \"radialGradient\", \"stop\", \"clipPath\", \"title\", \"desc\"].forEach(function (t) { SVG_EL[t] = 1; });");
L.push("  var SVG_AT = {};");
L.push("  [\"id\", \"xmlns\", \"version\", \"width\", \"height\", \"viewBox\", \"preserveAspectRatio\",");
L.push("   \"x\", \"y\", \"x1\", \"y1\", \"x2\", \"y2\", \"cx\", \"cy\", \"r\", \"rx\", \"ry\", \"fx\", \"fy\", \"fr\",");
L.push("   \"d\", \"points\", \"transform\", \"fill\", \"fill-opacity\", \"fill-rule\", \"stroke\", \"stroke-width\",");
L.push("   \"stroke-opacity\", \"stroke-linecap\", \"stroke-linejoin\", \"stroke-miterlimit\", \"stroke-dasharray\",");
L.push("   \"stroke-dashoffset\", \"opacity\", \"clip-path\", \"clip-rule\", \"clipPathUnits\",");
L.push("   \"gradientUnits\", \"gradientTransform\", \"spreadMethod\", \"offset\", \"stop-color\", \"stop-opacity\",");
L.push("   \"vector-effect\", \"shape-rendering\", \"color\"].forEach(function (t) { SVG_AT[t] = 1; });");
L.push("  function validerSvg(txt, w, h) {");
L.push("    if (txt.indexOf(\"&\") !== -1) throw new Error(\"SVG : entites interdites\");");
L.push("    if (/[\\u0000-\\u0008\\u000b\\u000c\\u000e-\\u001f]/.test(txt)) throw new Error(\"SVG : caracteres invalides\");");
L.push("    if (/<script|<style|<!ENTITY|<\\?xml-stylesheet|javascript:/i.test(txt)) throw new Error(\"SVG : contenu actif interdit\");");
L.push("    var p = 0, prof = 0, balises = [];");
L.push("    while (p < txt.length) {");
L.push("      var s = txt.indexOf(\"<\", p);");
L.push("      if (s < 0) break;");
L.push("      if (txt.slice(p, s).trim()) throw new Error(\"SVG : texte hors title/desc interdit\");");
L.push("      if (txt.startsWith(\"<!--\", s)) { var fc = txt.indexOf(\"-->\", s); if (fc < 0) throw new Error(\"SVG : commentaire non ferme\"); p = fc + 3; continue; }");
L.push("      var e = txt.indexOf(\">\", s);");
L.push("      if (e < 0) throw new Error(\"SVG : balise non fermee\");");
L.push("      var t = txt.slice(s + 1, e);");
L.push("      p = e + 1;");
L.push("      if (t.charAt(0) === \"/\") {");
L.push("        var ferm = t.slice(1).trim();");
L.push("        if (!/^[A-Za-z]+$/.test(ferm)) throw new Error(\"SVG : fermeture invalide\");");
L.push("        if (balises.pop() !== ferm) throw new Error(\"SVG : balises imbriquees incoherentes\");");
L.push("        continue;");
L.push("      }");
L.push("      var m = /^([A-Za-z]+)([\\s\\S]*?)(\\/?)$/.exec(t);");
L.push("      if (!m) throw new Error(\"SVG : balise illisible\");");
L.push("      var nom = m[1], brut = m[2] || \"\", auto = m[3] === \"/\";");
L.push("      if (!SVG_EL[nom]) throw new Error(\"SVG : element non autorise (« \" + nom + \" »)\");");
L.push("      prof++;");
L.push("      if (prof > 20000 || balises.length > 64) throw new Error(\"SVG : complexite excessive\");");
L.push("      var re = /\\s+([A-Za-z][A-Za-z0-9-]*)\\s*=\\s*(?:\"([^\"<]*)\"|'([^'<]*)')/g, mm;");
L.push("      var vus = {};");
L.push("      while ((mm = re.exec(brut))) {");
L.push("        var at = mm[1], va = (mm[2] !== undefined ? mm[2] : mm[3]) || \"\";");
L.push("        if (vus[at]) throw new Error(\"SVG : attribut duplique\");");
L.push("        vus[at] = 1;");
L.push("        if (!SVG_AT[at]) throw new Error(\"SVG : attribut non autorise (« \" + at + \" »)\");");
L.push("        if (va.length > 262144) throw new Error(\"SVG : attribut trop long\");");
L.push("        if (/url\\s*\\(/i.test(va)) {");
L.push("          if (!/^url\\(#[A-Za-z_][A-Za-z0-9_.-]*\\)$/.test(va)) throw new Error(\"SVG : reference url() interdite\");");
L.push("          if ([\"fill\", \"stroke\", \"clip-path\"].indexOf(at) === -1) throw new Error(\"SVG : url() hors fill/stroke/clip-path\");");
L.push("        }");
L.push("      }");
L.push("      if (nom === \"svg\") {");
L.push("        var vb = (vus.viewBox ? /([-\\d.]+)[\\s,]+([-\\d.]+)[\\s,]+([-\\d.]+)[\\s,]+([-\\d.]+)/.exec(brut) : null);");
L.push("        var lw = vus.width ? parseFloat((/width\\s*=\\s*\"(\\d+)/.exec(brut) || [])[1]) : NaN;");
L.push("        var lh = vus.height ? parseFloat((/height\\s*=\\s*\"(\\d+)/.exec(brut) || [])[1]) : NaN;");
L.push("        if (vus.xmlns === undefined) throw new Error(\"SVG : xmlns manquant\");");
L.push("        if (lw !== w || lh !== h) throw new Error(\"SVG : dimensions attendues \" + w + \"x\" + h + \" (recu \" + lw + \"x\" + lh + \")\");");
L.push("        if (!vb || Number(vb[3]) !== w || Number(vb[4]) !== h) throw new Error(\"SVG : viewBox doit valoir 0 0 \" + w + \" \" + h);");
L.push("      }");
L.push("      if (!auto) balises.push(nom);");
L.push("    }");
L.push("    if (balises.length) throw new Error(\"SVG : document incomplet\");");
L.push("    if (!prof) throw new Error(\"SVG : vide\");");
L.push("  }");
fs.writeFileSync("C:/tmp/theoverify/.workbuddy-ai/artifacts/_v586/_p2.txt", L.join("\r\n"), "utf8");
