/* v586 — morceau 1 : en-tete + parseur ZIP minimal + validation */
const fs = require("fs");
const L = [];
L.push("<script id=\"v586-pets-import\">");
L.push("(function () {");
L.push("  \"use strict\";");
L.push("  if (window.__v586Import) return;");
L.push("  /* Import de compagnons au format OpenPets (MIT) : paquet = pet.json +");
L.push("     spritesheet.webp|svg, fourni en .zip ou en deux fichiers. Validation");
L.push("     DEFENSIVE (proche du validateur officiel) avant tout stockage. */");
L.push("");
L.push("  /* ── 1. ZIP minimal : EOCD → repertoire central → DecompressionStream ── */");
L.push("  function u16(d, o) { return d[o] | (d[o + 1] << 8); }");
L.push("  function u32(d, o) { return (d[o] | (d[o + 1] << 8) | (d[o + 2] << 16) | (d[o + 3] << 24)) >>> 0; }");
L.push("  async function decompresser(brut, methode) {");
L.push("    if (methode === 0) return brut;");
L.push("    if (methode !== 8) throw new Error(\"Compression ZIP non geree (methode \" + methode + \")\");");
L.push("    if (typeof DecompressionStream !== \"function\") throw new Error(\"DecompressionStream indisponible\");");
L.push("    var ds = new DecompressionStream(\"deflate-raw\");");
L.push("    var flux = new Blob([brut]).stream().pipeThrough(ds);");
L.push("    return new Uint8Array(await new Response(flux).arrayBuffer());");
L.push("  }");
L.push("  async function lireZip(tampon) {");
L.push("    var d = new Uint8Array(tampon), i, eocd = -1;");
L.push("    for (i = d.length - 22; i >= 0 && i > d.length - 66000; i--) {");
L.push("      if (d[i] === 0x50 && d[i + 1] === 0x4b && d[i + 2] === 0x05 && d[i + 3] === 0x06) { eocd = i; break; }");
L.push("    }");
L.push("    if (eocd < 0) throw new Error(\"Archive ZIP invalide (EOCD absent)\");");
L.push("    var n = u16(d, eocd + 10), pos = u32(d, eocd + 16), sortie = {};");
L.push("    for (i = 0; i < n; i++) {");
L.push("      if (u32(d, pos) !== 0x02014b50) throw new Error(\"Repertoire central corrompu\");");
L.push("      var methode = u16(d, pos + 10), tailleC = u32(d, pos + 20);");
L.push("      var nLen = u16(d, pos + 28), eLen = u16(d, pos + 30), cLen = u16(d, pos + 32);");
L.push("      var decal = u32(d, pos + 42);");
L.push("      var nom = new TextDecoder().decode(d.slice(pos + 46, pos + 46 + nLen));");
L.push("      if (u32(d, decal) !== 0x04034b50) throw new Error(\"En-tete local invalide\");");
L.push("      var ln = u16(d, decal + 26), le = u16(d, decal + 28);");
L.push("      var debut = decal + 30 + ln + le;");
L.push("      if (tailleC > 8 * 1024 * 1024) throw new Error(\"Fichier trop gros dans l archive\");");
L.push("      sortie[nom] = await decompresser(d.slice(debut, debut + tailleC), methode);");
L.push("      pos += 46 + nLen + eLen + cLen;");
L.push("    }");
L.push("    return sortie;");
L.push("  }");
L.push("");
L.push("  /* ── 2. validation pet.json ── */");
L.push("  function validerPetJson(txt) {");
L.push("    var o;");
L.push("    try { o = JSON.parse(txt); } catch (e) { throw new Error(\"pet.json illisible (JSON)\"); }");
L.push("    if (!o || typeof o !== \"object\" || Array.isArray(o)) throw new Error(\"pet.json : objet attendu\");");
L.push("    var id = String(o.id || \"\").trim();");
L.push("    if (!/^[a-z0-9][a-z0-9-]{0,40}$/.test(id)) throw new Error(\"pet.json : id invalide (a-z, 0-9, tirets)\");");
L.push("    var chemin = String(o.spritesheetPath || \"\");");
L.push("    if (chemin !== \"spritesheet.webp\" && chemin !== \"spritesheet.svg\") throw new Error(\"pet.json : spritesheetPath doit etre spritesheet.webp ou spritesheet.svg\");");
L.push("    if (o.spriteVersionNumber !== undefined && o.spriteVersionNumber !== 2) throw new Error(\"pet.json : spriteVersionNumber doit valoir 2\");");
L.push("    return {");
L.push("      id: id,");
L.push("      nom: String(o.displayName || id).slice(0, 40),");
L.push("      desc: String(o.description || \"\").slice(0, 200),");
L.push("      chemin: chemin,");
L.push("      version: o.spriteVersionNumber === 2 ? 2 : 1");
L.push("    };");
L.push("  }");
fs.writeFileSync("C:/tmp/theoverify/.workbuddy-ai/artifacts/_v586/_p1.txt", L.join("\r\n"), "utf8");
