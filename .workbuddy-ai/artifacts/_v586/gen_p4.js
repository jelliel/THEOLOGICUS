L.push("    if (estSvg) {");
L.push("      validerSvg(new TextDecoder().decode(sprite), 1536, h);");
L.push("      meta.spritesheet = octetsVersDataUrl(sprite, \"image/svg+xml\");");
L.push("    } else {");
L.push("      await validerWebp(sprite, meta.version);");
L.push("      meta.spritesheet = octetsVersDataUrl(sprite, \"image/webp\");");
L.push("    }");
L.push("    await enregistrer(meta);");
L.push("    majSelecteur();");
