L.push("    var liste = Array.prototype.slice.call(fichiers || []);");
L.push("    if (!liste.length) throw new Error(\"aucun fichier\");");
L.push("    for (i = 0; i < liste.length; i++) {");
L.push("      f = liste[i];");
L.push("      if (/\\.zip$/i.test(f.name)) {");
L.push("        var entrees = await lireZip(await f.arrayBuffer());");
L.push("        for (var nom in entrees) {");
L.push("          if (/pet\\.json$/i.test(nom)) jsonTxt = new TextDecoder().decode(entrees[nom]);");
L.push("          else if (/spritesheet\\.svg$/i.test(nom)) { sprite = entrees[nom]; estSvg = true; }");
L.push("          else if (/spritesheet\\.webp$/i.test(nom)) { sprite = entrees[nom]; estSvg = false; }");
L.push("        }");
L.push("      } else if (/\\.json$/i.test(f.name)) {");
L.push("        jsonTxt = await f.text();");
L.push("      } else if (/\\.svg$/i.test(f.name)) {");
L.push("        sprite = new Uint8Array(await f.arrayBuffer()); estSvg = true;");
L.push("      } else if (/\\.webp$/i.test(f.name)) {");
L.push("        sprite = new Uint8Array(await f.arrayBuffer()); estSvg = false;");
L.push("      }");
L.push("    }");
L.push("    if (!jsonTxt) throw new Error(\"pet.json absent du paquet\");");
L.push("    var meta = validerPetJson(jsonTxt);");
L.push("    if (!sprite) throw new Error(\"spritesheet absent du paquet\");");
L.push("    if ((meta.chemin === \"spritesheet.svg\") !== estSvg) throw new Error(\"pet.json et spritesheet ne correspondent pas\");");
