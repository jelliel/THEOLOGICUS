L.push("  /* ── 4. validation du spritesheet WebP (signature + dimensions) ── */");
L.push("  async function validerWebp(octets, version) {");
L.push("    if (octets.length < 30) throw new Error(\"WebP : fichier trop petit\");");
L.push("    var sig = String.fromCharCode(octets[0], octets[1], octets[2], octets[3]);");
L.push("    var fmt = String.fromCharCode(octets[8], octets[9], octets[10], octets[11]);");
L.push("    if (sig !== \"RIFF\" || fmt !== \"WEBP\") throw new Error(\"WebP : signature invalide\");");
L.push("    var bmp;");
L.push("    try { bmp = await createImageBitmap(new Blob([octets], { type: \"image/webp\" })); }");
L.push("    catch (e) { throw new Error(\"WebP : image illisible\"); }");
L.push("    var attenduH = version === 2 ? 2288 : 1872;");
L.push("    if (bmp.width !== 1536 || bmp.height !== attenduH) {");
L.push("      try { bmp.close(); } catch (e2) {}");
L.push("      throw new Error(\"WebP : dimensions attendues 1536x\" + attenduH + \" (recu \" + bmp.width + \"x\" + bmp.height + \")\");");
L.push("    }");
L.push("    try { bmp.close(); } catch (e3) {}");
L.push("  }");
L.push("  function octetsVersDataUrl(octets, mime) {");
L.push("    var s = \"\", i, pas = 8192;");
L.push("    for (i = 0; i < octets.length; i += pas) s += String.fromCharCode.apply(null, octets.subarray(i, i + pas));");
L.push("    return \"data:\" + mime + \";base64,\" + btoa(s);");
L.push("  }");
