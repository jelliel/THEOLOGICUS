const fs = require("fs");
const L = [];
L.push("");
L.push("  /* ── feuille de style dynamique (image d atlas en regle CSS, jamais en style inline) ── */");
L.push("  var styleEl = document.createElement(\"style\");");
L.push("  styleEl.id = \"v584-style\";");
L.push("  var reglesAtlas = [];");
L.push("  function regleCss(sel, decl) { reglesAtlas.push(sel + \"{\" + decl + \"}\"); rafraichirStyle(); }");
L.push("  function cssBase() {");
L.push("    return \"#v584-pet{position:fixed;left:0;top:0;z-index:calc(var(--z-modal-lg,2000) - 100);\"");
L.push("      + \"pointer-events:none;background-repeat:no-repeat;transform:translate(-320px,-320px);\"");
L.push("      + \"transition:transform .55s cubic-bezier(.3,.9,.35,1);will-change:transform}\";");
L.push("  }");
L.push("  function tailleCourante() {");
L.push("    if (window.innerWidth < 640) return 60;");
L.push("    var t = parseInt(lit(\"theo_pets_taille\"), 10);");
L.push("    return (t === 60 || t === 76 || t === 96) ? t : 76;");
L.push("  }");
L.push("  function cssDynamique() {");
L.push("    var t = tailleCourante();");
L.push("    var k = t / FW, hs = R(FH * k), aws = R(AW * k), ahs = R(AH * k);");
L.push("    var s = \"#v584-pet{width:\" + t + \"px;height:\" + hs + \"px;background-size:\" + aws + \"px \" + ahs + \"px;}\";");
L.push("    var reduire = false;");
L.push("    try { reduire = window.matchMedia(\"(prefers-reduced-motion: reduce)\").matches; } catch (e) {}");
L.push("    var cleEtat, e, f, stops;");
L.push("    for (cleEtat in ETATS) {");
L.push("      e = ETATS[cleEtat];");
L.push("      if (reduire) {");
L.push("        if (cleEtat === \"idle\") s += \"#v584-pet[data-anim=\\\"idle\\\"]{background-position:0 0;}\";");
L.push("        continue;");
L.push("      }");
L.push("      s += \"#v584-pet[data-anim=\\\"\" + cleEtat + \"\\\"]{animation:v584-\" + cleEtat + \" \" + e.dur + \"s steps(1,end) infinite;}\";");
L.push("      stops = \"\";");
L.push("      for (f = 0; f < e.n; f++) {");
L.push("        stops += (f / e.n * 100).toFixed(4) + \"%{background-position:\" + R(-f * FW * k) + \"px \" + R(-e.row * FH * k) + \"px;}\";");
L.push("      }");
L.push("      s += \"@keyframes v584-\" + cleEtat + \"{\" + stops + \"}\";");
L.push("    }");
L.push("    return s;");
L.push("  }");
L.push("  function rafraichirStyle() { styleEl.textContent = cssBase() + cssDynamique() + reglesAtlas.join(\"\"); }");
L.push("  rafraichirStyle();");
L.push("  if (document.head) document.head.appendChild(styleEl);");
L.push("  else document.documentElement.appendChild(styleEl);");
L.push("");
L.push("  /* ── ancres : coin bas-gauche / composeur / message suivi ── */");
L.push("  var host = null, cibleNom = \"coin\";");
L.push("  function ciblePos(nom) {");
L.push("    var w = host ? host.offsetWidth : 76, h = host ? host.offsetHeight : 82;");
L.push("    var vw = window.innerWidth || 1024, vh = window.innerHeight || 768;");
L.push("    var mob = vw < 640, x = 14, y = vh - h - (mob ? 96 : 14);");
L.push("    if (nom === \"composeur\") {");
L.push("      var r = document.getElementById(\"input-area\");");
L.push("      var rr = r ? r.getBoundingClientRect() : null;");
L.push("      if (rr) { x = rr.left + 16; y = rr.top - h * 0.82; }");
L.push("    } else if (nom === \"message\") {");
L.push("      var ms = document.querySelectorAll(\"#chat-container .message\");");
L.push("      var m = ms.length ? ms[ms.length - 1] : null;");
L.push("      if (!m) return ciblePos(\"composeur\");");
L.push("      var mr = m.getBoundingClientRect();");
L.push("      x = mr.right - w * 0.7;");
L.push("      y = mr.top - h + 10;");
L.push("    }");
L.push("    x = Math.max(6, Math.min(x, vw - w - 6));");
L.push("    y = Math.max(6, Math.min(y, vh - h - 6));");
L.push("    return { x: R(x), y: R(y) };");
L.push("  }");
L.push("  function ancre(nom) {");
L.push("    if (!host) return;");
L.push("    cibleNom = nom;");
L.push("    var p = ciblePos(nom);");
L.push("    host.style.transform = \"translate(\" + p.x + \"px,\" + p.y + \"px)\";");
L.push("  }");
