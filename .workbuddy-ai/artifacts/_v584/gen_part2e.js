/* v584 — partie 2e : accessoires + creature (assembleur) + atlas SVG */
const fs = require("fs");
const L = [];
L.push("");
L.push("  function accessoire(def, p, etat, i) {");
L.push("    var s = \"\", q = p.quill || 0, h = i * 2.4;");
L.push("    if (def.acc === \"halo\") {");
L.push("      s += el(\"ellipse\", { cx: 96, cy: 34, rx: 26, ry: 8, fill: \"none\", stroke: \"#e5c15a\", \"stroke-width\": 4 });");
L.push("      s += el(\"ellipse\", { cx: 96, cy: 34, rx: 26, ry: 8, fill: \"none\", stroke: \"#fff3c4\", \"stroke-width\": 1.6 });");
L.push("    } else if (def.acc === \"livre\") {");
L.push("      s += el(\"rect\", { x: 116, y: R(150 + q * 0.3), width: 34, height: 24, rx: 3, fill: \"#8f4a2a\", stroke: \"#5e2f18\", \"stroke-width\": 2, transform: \"rotate(-8 133 \" + R(162 + q * 0.3) + \")\" });");
L.push("      s += el(\"line\", { x1: 133, y1: R(150 + q * 0.3), x2: 133, y2: R(174 + q * 0.3), stroke: \"#fff3c4\", \"stroke-width\": 2, transform: \"rotate(-8 133 \" + R(162 + q * 0.3) + \")\" });");
L.push("    } else if (def.acc === \"bulles\") {");
L.push("      s += el(\"circle\", { cx: 146, cy: R(96 - h), r: 3, fill: \"none\", stroke: \"#bfe6f7\", \"stroke-width\": 1.6 });");
L.push("      s += el(\"circle\", { cx: 154, cy: R(78 - h * 1.4), r: 4.4, fill: \"none\", stroke: \"#bfe6f7\", \"stroke-width\": 1.6 });");
L.push("      s += el(\"circle\", { cx: 142, cy: R(62 - h * 1.8), r: 2.4, fill: \"none\", stroke: \"#bfe6f7\", \"stroke-width\": 1.4 });");
L.push("    } else if (def.acc === \"etoile\") {");
L.push("      s += etoile(150, 34, 9, \"#ffd166\", 0.9);");
L.push("      s += etoile(134, 48, 5, \"#ffe8a3\", 0.7);");
L.push("    } else if (def.acc === \"braises\") {");
L.push("      s += etoile(148, 70, 4, \"#ffb347\", 0.5);");
L.push("      s += etincelles(p);");
L.push("    }");
L.push("    return s;");
L.push("  }");
L.push("");
L.push("  function creature(def, etat, i) {");
L.push("    var p = params(etat, i), s = \"\";");
L.push("    s += el(\"ellipse\", { cx: 96, cy: 196, rx: R(Math.max(24, 50 - p.jump)), ry: 7, fill: \"rgba(15,25,45,0.20)\" });");
L.push("    s += \"<g transform=\\\"translate(0,\" + R(-(p.bob + p.jump)) + \")\\\">\";");
L.push("    var cle = def.cle;");
L.push("    if (cle === \"cierge\") s += cierge(def, p);");
L.push("    else if (cle === \"lion\") s += lion(def, p);");
L.push("    else if (cle === \"poisson\") s += poisson(def, p);");
L.push("    else if (cle === \"fennec\") s += fennec(def, p);");
L.push("    else if (cle === \"chouette\") s += chouette(def, p);");
L.push("    else s += oiseau(def, p);");
L.push("    s += accessoire(def, p, etat, i);");
L.push("    s += pensee(p);");
L.push("    s += \"</g>\";");
L.push("    return s;");
L.push("  }");
L.push("");
L.push("  function atlasSvg(cle) {");
L.push("    var def = MASC[cle];");
L.push("    def.cle = cle;");
L.push("    var out = [\"<svg xmlns=\\\"http://www.w3.org/2000/svg\\\" width=\\\"1536\\\" height=\\\"2288\\\" viewBox=\\\"0 0 1536 2288\\\">\"];");
L.push("    var e, f, cleEtat;");
L.push("    for (cleEtat in ETATS) {");
L.push("      e = ETATS[cleEtat];");
L.push("      for (f = 0; f < e.n; f++) {");
L.push("        out.push(\"<g transform=\\\"translate(\" + (f * FW) + \",\" + (e.row * FH) + \")\\\">\");");
L.push("        out.push(creature(def, cleEtat, f));");
L.push("        out.push(\"</g>\");");
L.push("      }");
L.push("    }");
L.push("    out.push(\"</svg>\");");
L.push("    return out.join(\"\");");
L.push("  }");
