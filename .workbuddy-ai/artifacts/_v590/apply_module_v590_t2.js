/* v590 — tranche 2 : APPARIEMENT référence ↔ texte cité.
   Le module v590-citations est REMPLACÉ par sa version T1+T2 (remplacement du
   bloc entier par TRANCHES : plus sûr que des ancres internes sur du code que
   je viens d'écrire). CRLF rétabli, </script> vérifié, node --check du module
   extrait. */
const fs = require("fs"), path = require("path");
const F = path.join(__dirname, "..", "..", "..", "THEOLOGICUS.html");
let html = fs.readFileSync(F, "utf8");

const DEB = '<script id="v590-citations">';
const start = html.indexOf(DEB);
if (start < 0) { console.error("module v590 introuvable"); process.exit(1); }
const finTag = html.indexOf("</script>", start);
if (finTag < 0) { console.error("fermeture introuvable"); process.exit(1); }
const fin = finTag + "</script>".length;

const MODULE = [
'<script id="v590-citations">',
'/* v590 — VÉRIFICATION DE FIDÉLITÉ DES CITATIONS.',
'   T1 : le comparateur (texte cité ↔ texte réel du corpus).',
'   T2 : l\'appariement référence ↔ texte cité.',
'',
'   Constat VÉRIFIÉ : initVerifyMarks() (l.27539) marque déjà les références',
'   bibliques/coraniques ✅/⚠️/✏️ — mais à partir des SEULS NUMÉROS du verset.',
'   Le ✅ porte donc sur la RÉFÉRENCE, jamais sur le TEXTE CITÉ : une réponse',
'   peut écrire « Jn 3,16 : "Dieu a tant aimé le monde qu\'il a donné son Fils',
'   unique" » et obtenir ✅ avec un texte ALTÉRÉ.',
'   ADDITIF et INERTE au chargement : aucun DOM, aucun réseau, aucun minuteur. */',
'(function () {',
'  "use strict";',
'  if (window.__v590Citations) return;',
'',
'  /* ═══════════ T1 — comparateur ═══════════ */',
'  /* conforme = TOUS les mots cités sont dans le verset, dans l\'ordre.',
'     approximatif = la citation reste proche mais un mot diverge.',
'     divergent = ce n\'est pas une citation de ce texte (paraphrase incluse).',
'     Seuils calibrés par le banc _v590 ; toute modification doit passer par lui. */',
'  var SEUILS = { approximatif: 0.8 };',
'  var MIN_JETONS = 3;      /* en deçà, « conforme » ne prouverait rien */',
'  var MAX_CAR = 2000;      /* au-delà, ce n\'est plus un verset : on ne compare pas */',
'',
'  /* Normalisation PARTAGÉE : les deux textes passent par la MÊME fonction.',
'     Sans elle, les variantes typographiques légitimes (« » vs " ", ’ vs \',',
'     accents, majuscules) produiraient des « divergents » qui n\'en sont pas. */',
'  function normaliser(s) {',
'    if (s == null) return "";',
'    var t = String(s);',
'    try { t = t.normalize("NFD").replace(/[\\u0300-\\u036f]/g, ""); } catch (e) {}',
'    t = t.toLowerCase().replace(/[^a-z0-9]+/g, " ");',
'    return t.replace(/\\s+/g, " ").trim();',
'  }',
'  function R3(n) { return Math.round(n * 1000) / 1000; }',
'',
'  /* Longueur de la plus longue sous-séquence commune, à deux lignes de mémoire. */',
'  function sousSequence(a, b) {',
'    var n = a.length, m = b.length, i, j, prev, cur, tmp;',
'    if (!n || !m) return 0;',
'    prev = new Array(m + 1);',
'    cur = new Array(m + 1);',
'    for (j = 0; j <= m; j++) prev[j] = 0;',
'    for (i = 1; i <= n; i++) {',
'      cur[0] = 0;',
'      for (j = 1; j <= m; j++) {',
'        cur[j] = (a[i - 1] === b[j - 1]) ? (prev[j - 1] + 1) : Math.max(prev[j], cur[j - 1]);',
'      }',
'      tmp = prev; prev = cur; cur = tmp;',
'    }',
'    return prev[m];',
'  }',
'',
'  /* comparer(texte cité, texte réel du corpus) → {verdict, score, partiel?}',
'     La comparaison porte sur la FORME. Une reformulation qui conserve le sens',
'     mais change les mots ressort en « divergent » : c\'est voulu (ce n\'est pas',
'     une citation). La fidélité SÉMANTIQUE n\'est pas de notre ressort. */',
'  function comparer(cite, reel) {',
'    var c = normaliser(cite), r = normaliser(reel);',
'    if (!c || !r) return { verdict: "indetermine", score: 0, motif: "entree-vide" };',
'    if (c.length > MAX_CAR || r.length > MAX_CAR) return { verdict: "indetermine", score: 0, motif: "trop-long" };',
'    if (c === r) return { verdict: "conforme", score: 1, partiel: false };',
'    var A = c.split(" "), B = r.split(" ");',
'    if (A.length < MIN_JETONS) return { verdict: "indetermine", score: 0, motif: "trop-court" };',
'    var couv = sousSequence(A, B) / A.length;',
'    if (couv === 1) return { verdict: "conforme", score: 1, partiel: (A.length < B.length) };',
'    if (couv >= SEUILS.approximatif) return { verdict: "approximatif", score: R3(couv), partiel: false };',
'    return { verdict: "divergent", score: R3(couv), partiel: false };',
'  }',
'',
'  /* ═══════════ T2 — appariement référence ↔ texte cité ═══════════',
'     L\'appareil existant travaille sur des éléments `.bible-ref` DÉJÀ rendus :',
'     la référence est identifiée et sa POSITION dans le DOM est connue — on ne',
'     re-parse donc PAS le texte (pas de duplication du parseur existant).',
'     Règle CONSERVATRICE : la citation doit être DÉLIMITÉE (« » " " “ ”) ET',
'     commencer à moins de PROXIMITE caractères de la référence. Sans citation',
'     délimitée, on ne devine PAS : mieux vaut ne rien dire que se tromper. */',
'  var PROXIMITE = 40;',
'  var MIN_CITE = 8;',
'  var SEP_TETE = /^[\\s:;,.\\u2014\\u2013\\u2026()\\-]+/;',
'  var SEP_QUEUE = /[\\s:;,.\\u2014\\u2013\\u2026()\\-]+$/;',
'  var PAIRES = [["\\u00ab", "\\u00bb"], ["\\u201c", "\\u201d"], ["\\"", "\\""]];',
'  var OUVRANTS = {}, FERMANTS = {};',
'  for (var _i = 0; _i < PAIRES.length; _i++) { OUVRANTS[PAIRES[_i][0]] = PAIRES[_i][1]; FERMANTS[PAIRES[_i][1]] = PAIRES[_i][0]; }',
'',
'  /* Texte du même bloc, APRÈS / AVANT l\'élément (borné : au-delà de 400',
'     caractères ce n\'est plus la citation de CETTE référence). */',
'  function texteApres(el, max) {',
'    var p = el.parentNode; if (!p) return "";',
'    try {',
'      var r = document.createRange();',
'      r.setStartAfter(el);',
'      r.setEnd(p, p.childNodes.length);',
'      return r.toString().slice(0, max || 400);',
'    } catch (e) { return ""; }',
'  }',
'  function texteAvant(el, max) {',
'    var p = el.parentNode; if (!p) return "";',
'    try {',
'      var r = document.createRange();',
'      r.setStart(p, 0);',
'      r.setEndBefore(el);',
'      var t = r.toString();',
'      return t.slice(Math.max(0, t.length - (max || 400)));',
'    } catch (e) { return ""; }',
'  }',
'  /* Citation ouvrante (« … » / " … " / “ … ”) en tête du texte après la',
'     référence. Le garde-fou de proximité écarte les citations lointaines. */',
'  function citationOuvrante(txt) {',
'    var s = String(txt).replace(SEP_TETE, "");',
'    if (String(txt).length - s.length > PROXIMITE) return null;',
'    var fermant = OUVRANTS[s.charAt(0)];',
'    if (!fermant) return null;',
'    var fin = s.indexOf(fermant, 1);',
'    if (fin < 0) return null;',
'    return s.slice(1, fin);',
'  }',
'  /* Citation fermante (… « ) juste AVANT la référence. */',
'  function citationFermante(txt) {',
'    var t = String(txt).replace(SEP_QUEUE, "");',
'    if (String(txt).length - t.length > PROXIMITE) return null;',
'    var c = t.charAt(t.length - 1);',
'    var ouvrant = FERMANTS[c];',
'    if (!ouvrant) return null;',
'    var deb = t.lastIndexOf(ouvrant, t.length - 2);',
'    if (deb < 0) return null;',
'    return t.slice(deb + 1, t.length - 1);',
'  }',
'  /* {cite, sens} pour un élément de référence, ou null si rien de sûr. */',
'  function citationAssociee(el) {',
'    if (!el) return null;',
'    var a = citationOuvrante(texteApres(el));',
'    if (a && a.length >= MIN_CITE) return { cite: a, sens: "apres" };',
'    var b = citationFermante(texteAvant(el));',
'    if (b && b.length >= MIN_CITE) return { cite: b, sens: "avant" };',
'    return null;',
'  }',
'  /* Toutes les citations appariables d\'un conteneur (corps d\'un message).',
'     La résolution du texte réel du corpus reste à la charge de l\'appelant',
'     (T3) : elle exige le corpus chargé, ce module n\'y touche pas. */',
'  function citationsDuBloc(racine) {',
'    var out = [];',
'    var refs = (racine || document).querySelectorAll("a.bible-ref, span.bible-ref");',
'    Array.prototype.forEach.call(refs, function (el) {',
'      var c = citationAssociee(el);',
'      if (!c) return;',
'      var ref = String(el.textContent || "").trim();',
'      var p = null;',
'      try { p = window.__parseBibleRef ? window.__parseBibleRef(ref) : null; } catch (e) { p = null; }',
'      out.push({ el: el, ref: ref, cite: c.cite, sens: c.sens, parse: p });',
'    });',
'    return out;',
'  }',
'',
'  window.__v590Citations = {',
'    comparer: comparer,',
'    normaliser: normaliser,',
'    citationAssociee: citationAssociee,',
'    citationsDuBloc: citationsDuBloc,',
'    SEUILS: SEUILS,',
'    MIN_JETONS: MIN_JETONS,',
'    MAX_CAR: MAX_CAR,',
'    PROXIMITE: PROXIMITE,',
'    MIN_CITE: MIN_CITE',
'  };',
'})();',
'</script>'
].join("\n");

const nouveau = html.slice(0, start) + MODULE.replace(/\n/g, "\r\n") + html.slice(fin);
if (nouveau.indexOf("</body>") < 0) { console.error("</body> disparu"); process.exit(1); }
const crlf = nouveau.replace(/\r\n/g, "\n").replace(/\n/g, "\r\n");
fs.writeFileSync(F, crlf, "utf8");

const i2 = crlf.indexOf(DEB), f2 = crlf.indexOf("</script>", i2);
const js = crlf.slice(i2 + DEB.length, f2);
fs.writeFileSync(path.join(__dirname, "module_v590.js"), js, "utf8");
console.log("module v590 (T1+T2) remplace — " + js.length + " octets de JS extraits");
